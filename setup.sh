#!/usr/bin/env bash
# Configuration screen for the RAG demo: review and edit every setting, then deploy.
#
#   ./setup.sh                 interactive screen (default when run in a terminal)
#   ./setup.sh sk-...          no screen: create .env with this OpenAI key if it does not exist
#   ./setup.sh --interactive   force the screen even if stdin is not a terminal (testing)
set -euo pipefail
cd "$(dirname "$0")"
trap 'stty echo 2>/dev/null || true' EXIT

ENV_FILE=.env
rand() { openssl rand -hex "$1"; }

# ---------- defaults ----------
POSTGRES_USER=rag
POSTGRES_PASSWORD=
POSTGRES_DB=rag
N8N_ENCRYPTION_KEY=
N8N_PORT=5678
GENERIC_TIMEZONE=America/Bogota
OWNER_EMAIL=admin@example.com
OWNER_PASSWORD=
OWNER_FIRST_NAME=Demo
OWNER_LAST_NAME=RAG
OPENAI_API_KEY=

EXISTING=0

# ---------- load an existing .env (never `source` it) ----------
if [ -f "$ENV_FILE" ]; then
  EXISTING=1
  while IFS= read -r line || [ -n "$line" ]; do
    case "$line" in ''|'#'*) continue ;; esac
    k=${line%%=*}
    v=${line#*=}
    case "$k" in
      POSTGRES_USER|POSTGRES_PASSWORD|POSTGRES_DB|N8N_ENCRYPTION_KEY|N8N_PORT|GENERIC_TIMEZONE|\
      OWNER_EMAIL|OWNER_PASSWORD|OWNER_FIRST_NAME|OWNER_LAST_NAME|OPENAI_API_KEY)
        printf -v "$k" '%s' "$v"
        ;;
    esac
  done < "$ENV_FILE"
fi

# ---------- fill generated secrets (placeholders count as empty) ----------
case "$POSTGRES_PASSWORD"   in ''|change_me*) POSTGRES_PASSWORD=$(rand 12) ;; esac
case "$N8N_ENCRYPTION_KEY"  in ''|change_me*) N8N_ENCRYPTION_KEY=$(rand 24) ;; esac
case "$OWNER_PASSWORD" in
  change_me*) OWNER_PASSWORD="Demo$(rand 5)1" ;;
  '') # A brand-new .env gets an admin; an existing one without the key keeps its manual admin.
      if [ "$EXISTING" = 0 ]; then OWNER_PASSWORD="Demo$(rand 5)1"; fi ;;
esac

# ---------- non-interactive mode ----------
INTERACTIVE=0
if [ "${1:-}" = "--interactive" ]; then
  INTERACTIVE=1
elif [ -t 0 ] && [ -z "${1:-}" ]; then
  INTERACTIVE=1
fi

write_env() {
  local tmp="${ENV_FILE}.tmp"
  {
    echo "# Generated by ./setup.sh - edit with ./setup.sh or by hand."
    echo "POSTGRES_USER=$POSTGRES_USER"
    echo "POSTGRES_PASSWORD=$POSTGRES_PASSWORD"
    echo "POSTGRES_DB=$POSTGRES_DB"
    echo "N8N_ENCRYPTION_KEY=$N8N_ENCRYPTION_KEY"
    echo "N8N_PORT=$N8N_PORT"
    echo "GENERIC_TIMEZONE=$GENERIC_TIMEZONE"
    echo "OWNER_EMAIL=$OWNER_EMAIL"
    echo "OWNER_PASSWORD=$OWNER_PASSWORD"
    echo "OWNER_FIRST_NAME=$OWNER_FIRST_NAME"
    echo "OWNER_LAST_NAME=$OWNER_LAST_NAME"
    echo "OPENAI_API_KEY=$OPENAI_API_KEY"
  } > "$tmp"
  chmod 600 "$tmp"
  mv "$tmp" "$ENV_FILE"
}

if [ "$INTERACTIVE" = 0 ]; then
  if [ "$EXISTING" = 1 ]; then
    echo ".env already exists, leaving it untouched. Run ./setup.sh in a terminal to edit it."
    exit 0
  fi
  OPENAI_API_KEY="${1:-}"
  write_env
  echo ".env created."
  echo "  n8n URL : http://localhost:$N8N_PORT"
  echo "  user    : $OWNER_EMAIL"
  echo "  password: $OWNER_PASSWORD"
  [ -n "$OPENAI_API_KEY" ] || echo "  WARNING : OPENAI_API_KEY is empty. Run ./setup.sh again to set it."
  echo
  echo "Next: docker compose up -d"
  exit 0
fi

# ---------- interactive screen ----------
SHOW=0
LOCKED=0
if command -v docker >/dev/null 2>&1 && [ -n "$(docker compose ps -a -q db 2>/dev/null || true)" ]; then
  LOCKED=1
fi

mask() {
  local v=$1
  if [ -z "$v" ]; then printf '(empty)'; return; fi
  if [ "$SHOW" = 1 ]; then printf '%s' "$v"; return; fi
  if [ "${#v}" -le 8 ]; then printf '********'; else printf '%s...%s' "${v:0:3}" "${v: -4}"; fi
}

screen() {
  clear 2>/dev/null || printf '\n\n'
  echo "+----------------------------------------------------------------+"
  echo "|  RAG demo (n8n + pgvector) - configuration                     |"
  echo "+----------------------------------------------------------------+"
  echo
  echo "  Editable"
  printf '   1) OpenAI API key        %s\n' "$(mask "$OPENAI_API_KEY")"
  printf '   2) Admin email           %s\n' "$OWNER_EMAIL"
  if [ -z "$OWNER_PASSWORD" ]; then
    printf '   3) Admin password        (empty: no admin is created or changed automatically)\n'
  else
    printf '   3) Admin password        %s\n' "$(mask "$OWNER_PASSWORD")"
  fi
  printf '   4) Admin name            %s %s\n' "$OWNER_FIRST_NAME" "$OWNER_LAST_NAME"
  printf '   5) n8n port (localhost)  %s\n' "$N8N_PORT"
  printf '   6) Timezone              %s\n' "$GENERIC_TIMEZONE"
  echo
  if [ "$LOCKED" = 1 ]; then
    echo "  Generated - LOCKED (already deployed; changing them would break the data)"
  else
    echo "  Generated automatically"
  fi
  printf '   7) Database password     %s\n' "$(mask "$POSTGRES_PASSWORD")"
  printf '   8) n8n encryption key    %s\n' "$(mask "$N8N_ENCRYPTION_KEY")"
  echo
  echo "  Fixed: database '$POSTGRES_DB', user '$POSTGRES_USER', models text-embedding-3-small + gpt-4o-mini"
  echo
  [ -z "$OPENAI_API_KEY" ] && echo "  ! OpenAI API key is empty: ingestion and chat will not work."
  echo
  echo "  [1-8] edit   [v] show/hide secrets   [s] save   [d] save and deploy   [q] quit"
  echo
}

ask() { # ask "prompt" -> REPLY (visible)
  read -r -p "  $1 " REPLY || REPLY=""
}
ask_secret() { # ask_secret "prompt" -> REPLY (hidden)
  read -r -s -p "  $1 " REPLY || REPLY=""
  echo
}
confirm() { # confirm "question" -> 0 if yes
  local a
  read -r -p "  $1 [y/N] " a || a=""
  case "$a" in y|Y|s|S|yes|si) return 0 ;; *) return 1 ;; esac
}
bad_chars() { # passwords/keys must be safe inside a .env file
  case "$1" in *[[:space:]\$\#\\\"\'\`]*) return 0 ;; *) return 1 ;; esac
}
note() { echo "  -> $1"; sleep 1.2; }

edit_field() {
  case "$1" in
    1)
      ask_secret "OpenAI API key (Enter keeps current, '-' clears):"
      case "$REPLY" in
        '') return ;;
        '-') OPENAI_API_KEY="" ;;
        *)
          if bad_chars "$REPLY"; then note "Rejected: no spaces, quotes, \$, # or backslashes."; return; fi
          case "$REPLY" in sk-*) ;; *) confirm "It does not start with 'sk-'. Use it anyway?" || return ;; esac
          OPENAI_API_KEY="$REPLY" ;;
      esac ;;
    2)
      ask "Admin email [$OWNER_EMAIL]:"
      [ -z "$REPLY" ] && return
      case "$REPLY" in
        *[[:space:]]*|*@*@*|@*|*@|*@*.) note "Not a valid email."; return ;;
        *@*.*) OWNER_EMAIL="$REPLY" ;;
        *) note "Not a valid email."; return ;;
      esac ;;
    3)
      ask_secret "Admin password (8+ chars, 1 number, 1 uppercase; 'g' generate, '-' clear, Enter keep):"
      case "$REPLY" in
        '') return ;;
        '-') OWNER_PASSWORD="" ;;
        g|G) OWNER_PASSWORD="Demo$(rand 5)1"; SHOW=1; note "Generated: $OWNER_PASSWORD" ;;
        *)
          if bad_chars "$REPLY"; then note "Rejected: no spaces, quotes, \$, # or backslashes."; return; fi
          if [ "${#REPLY}" -lt 8 ]; then note "Too short (8+ characters)."; return; fi
          case "$REPLY" in *[0-9]*) ;; *) note "Needs at least 1 number."; return ;; esac
          case "$REPLY" in *[A-Z]*) ;; *) note "Needs at least 1 uppercase letter."; return ;; esac
          OWNER_PASSWORD="$REPLY" ;;
      esac ;;
    4)
      ask "First name [$OWNER_FIRST_NAME]:"; [ -n "$REPLY" ] && OWNER_FIRST_NAME="$REPLY"
      ask "Last name  [$OWNER_LAST_NAME]:";  [ -n "$REPLY" ] && OWNER_LAST_NAME="$REPLY"
      return ;;
    5)
      ask "Port [$N8N_PORT]:"
      [ -z "$REPLY" ] && return
      case "$REPLY" in
        *[!0-9]*) note "Digits only."; return ;;
      esac
      if [ "$REPLY" -lt 1024 ] || [ "$REPLY" -gt 65535 ]; then note "Use a port between 1024 and 65535."; return; fi
      N8N_PORT="$REPLY" ;;
    6)
      ask "Timezone [$GENERIC_TIMEZONE]:"
      [ -z "$REPLY" ] && return
      case "$REPLY" in *[[:space:]]*) note "No spaces (example: America/Bogota)."; return ;; esac
      GENERIC_TIMEZONE="$REPLY" ;;
    7|8)
      if [ "$LOCKED" = 1 ]; then note "Locked: the stack is already deployed. Use 'docker compose down -v' first to reset."; return; fi
      confirm "Generate a new random value?" || return
      if [ "$1" = 7 ]; then POSTGRES_PASSWORD=$(rand 12); else N8N_ENCRYPTION_KEY=$(rand 24); fi ;;
    *) ;;
  esac
}

deploy() {
  command -v docker >/dev/null 2>&1 || { note "Docker is not installed or not in PATH."; return; }
  write_env
  echo
  echo "  Saved .env. Deploying..."
  if [ "$LOCKED" = 1 ]; then
    docker compose up -d --force-recreate n8n
  else
    docker compose up -d
  fi
  echo
  echo "  Waiting for n8n on http://localhost:$N8N_PORT ..."
  local i
  for i in $(seq 1 45); do
    if curl -fsS -m 3 "http://127.0.0.1:$N8N_PORT/healthz" >/dev/null 2>&1; then
      echo
      echo "  Ready: http://localhost:$N8N_PORT"
      if [ -n "$OWNER_PASSWORD" ]; then
        echo "  Login: $OWNER_EMAIL / (the admin password you set above)"
      else
        echo "  Login: your existing n8n account (no admin is managed from .env)."
      fi
      return
    fi
    sleep 2
  done
  echo "  n8n did not answer in 90 s. Check: docker compose logs n8n"
}

while true; do
  screen
  read -r -p "  > " CHOICE || CHOICE="q"
  case "$CHOICE" in
    [1-8]) edit_field "$CHOICE" ;;
    v|V) if [ "$SHOW" = 1 ]; then SHOW=0; else SHOW=1; fi ;;
    s|S) write_env; note "Saved to $ENV_FILE (permissions 600)." ;;
    d|D)
      screen
      if confirm "Deploy with this configuration?"; then deploy; break; fi ;;
    q|Q) echo; echo "  Exited without saving."; exit 0 ;;
    *) ;;
  esac
done
